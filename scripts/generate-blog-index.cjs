const fs = require('fs')
const path = require('path')
const fm = require('front-matter')

const languages = ['es', 'en']
const contentDir = path.resolve(__dirname, '..', 'src', 'content', 'blog')

const index = {}

for (const lang of languages) {
  const dir = path.join(contentDir, lang)
  if (!fs.existsSync(dir)) { index[lang] = []; continue }

  const files = fs.readdirSync(dir).filter(f => f.endsWith('.md'))
  index[lang] = files.map(file => {
    const raw = fs.readFileSync(path.join(dir, file), 'utf-8')
    const { attributes } = fm(raw)
    return {
      slug: file.replace('.md', ''),
      title: attributes.title || '',
      excerpt: attributes.excerpt || '',
      date: attributes.date || '',
      category: attributes.category || 'General',
      author: attributes.author || 'Goals Team',
      tags: attributes.tags || [],
    }
  }).sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
}

const output = `// Auto-generated by scripts/generate-blog-index.cjs — DO NOT EDIT
export type BlogPostMeta = {
  slug: string
  title: string
  excerpt: string
  date: string
  category: string
  author: string
  tags: string[]
}

export const blogIndex: Record<string, BlogPostMeta[]> = ${JSON.stringify(index, null, 2)}
`

fs.writeFileSync(path.resolve(__dirname, '..', 'src', 'data', 'blogIndex.ts'), output)
console.log('✓ Blog index generated')
